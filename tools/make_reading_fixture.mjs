// Writes tests/fixtures/readings.json from the JS reading engine (static/reading_engine.js): interpretations the
// Python port (web/reading.py) must reproduce exactly (pure text and integers, no floats, so exact on every platform).
// `node tools/make_reading_fixture.mjs --check` compares instead.
import { readFileSync, writeFileSync } from 'node:fs';
import { SPREADS, drawReading } from '../static/engine.js';
import { interpret } from '../static/reading_engine.js';
import { classifyQuestion } from '../static/reading_patterns.js';

const OUT = new URL('../tests/fixtures/readings.json', import.meta.url);
const QUESTIONS = ['', 'Will he come back to me?', 'Should I take the new job or stay where I am?',
  'Can I afford to move out this year?', 'What do I need to know about my studies?', 'Should I choose A or B?',
  'Will my operation go well?', 'Will I win the court case?', 'Should I put my savings into crypto?',
  'I want to end my life', '  “Quoted” question with é, ✨ and {braces} $1  ', 'WHAT ABOUT MY BOSS?'];
const TONES = ['traditional', 'modern', 'brief'];
// Constructed spreads that exercise particular patterns (ids, '-' = reversed).
const BUILT = [
  ['celtic', ['ar16', 'ar19', 'ar17', 'pe10', 'sw10', 'wa06', 'wa03', 'sw05', 'sw09', 'ar21'], 'cu13'],
  ['celtic', ['wa11', 'cu12', 'sw13', 'pe14', 'wa01', 'cu03', 'sw05', 'pe07', 'ar09', 'cu14'], null],
  ['celtic', ['wa11', 'cu11', 'sw11', 'pe11', '-ar02', '-ar03', '-ar04', '-ar05', '-ar06', '-ar07'], 'ar00'],
  ['celtic', ['cu01', 'cu02', 'cu03', 'cu04', 'wa05', 'wa06', 'ar00', 'ar01', 'cu09', 'wa10'], 'cu14'],
  ['three', ['wa01', 'cu02', 'sw03'], null], ['three', ['wa10', 'cu09', 'sw08'], null],
  ['three', ['wa02', 'cu05', 'wa09'], null], ['three', ['sw02', 'sw05', 'sw09'], null],
  ['three', ['ar16', '-cu04', 'ar17'], null], ['four', ['-wa05', '-cu05', '-sw05', 'pe05'], null],
];

function built(spread, list, significator, seed) {
  return { seed, spread, cutAt: 1, reversals: true, significator,
    cards: list.map((x, i) => ({ pos: SPREADS[spread].positions[i], id: x.replace('-', ''), reversed: x.startsWith('-') })) };
}

export function fixture() {
  const cases = [];
  let k = 0;
  for (const spread of Object.keys(SPREADS)) {
    for (const seed of [0, 7, 99, 123456, 4294967295]) {
      const significator = spread === 'celtic' && seed % 2 ? 'pe13' : null;
      const reading = drawReading({ seed, spread, significator, reversals: seed !== 99 });
      const question = QUESTIONS[k % QUESTIONS.length], tone = TONES[k % 3];
      cases.push({ reading, question, tone, out: interpret(reading, { question, tone }) });
      k++;
    }
  }
  for (const tone of TONES) { // shared links whose question was kept private
    const reading = drawReading({ seed: 77, spread: 'celtic' });
    cases.push({ reading, question: '', tone, withheld: true, out: interpret(reading, { tone, questionWithheld: true }) });
  }
  BUILT.forEach(([spread, list, sig], i) => {
    for (const tone of TONES) {
      const reading = built(spread, list, sig, 1000 + i), question = QUESTIONS[(i + TONES.indexOf(tone)) % QUESTIONS.length];
      cases.push({ reading, question, tone, out: interpret(reading, { question, tone }) });
    }
  });
  return {
    _doc: 'Generated by tools/make_reading_fixture.mjs from static/reading_engine.js; checked by tests/reading_fixture.test.mjs (JS) and tests/test_reading.py (Python port).',
    classify: QUESTIONS.map(q => [q, classifyQuestion(q)]),
    cases,
  };
}

// One case per line keeps the file readable in diffs.
export const fixtureText = () => {
  const f = fixture();
  return '{"_doc": ' + JSON.stringify(f._doc) + ',\n"classify": ' + JSON.stringify(f.classify) + ',\n"cases": [\n'
    + f.cases.map(c => JSON.stringify(c)).join(',\n') + '\n]}\n';
};

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === fixtureText();
    console.log(same ? 'fixture is current' : 'fixture is out of date: run node tools/make_reading_fixture.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, fixtureText());
  console.log('wrote', OUT.pathname);
}

// Writes tests/fixtures/engine.json from the JS engine (static/engine.js, core.js rng): the reference values the
// Python port (web/engine.py) must reproduce. `node tools/make_engine_fixture.mjs --check` compares instead.
import { readFileSync, writeFileSync } from 'node:fs';
import { CARDS, SPREADS, shuffle, cut, seedFrom, drawReading, recurrences } from '../static/engine.js';
import { rng } from '../static/core.js';

const OUT = new URL('../tests/fixtures/engine.json', import.meta.url);

export function fixture() {
  const seeds = [0, 1, 7, 42, 99, 123456, 2147483647, 2147483648, 4294967295];
  const rngs = Object.fromEntries(seeds.map(s => { const r = rng(s); return [s, Array.from({ length: 8 }, r)]; }));
  const texts = ['', 'a', 'daily 2026-11-13', '2026-11-11', 'Will the tests pass?', 'émoji ✨ 🂡 tarot'];
  const ids = CARDS.map(c => c.id);
  const draws = [];
  for (const spread of Object.keys(SPREADS)) {
    for (const seed of [0, 7, 99, 123456, 4294967295]) {
      draws.push({ args: { seed, spread }, out: drawReading({ seed, spread }) });
      draws.push({ args: { seed, spread, cutAt: 33, reversals: false }, out: drawReading({ seed, spread, cutAt: 33, reversals: false }) });
    }
  }
  for (const sig of ['cu13', 'ar00', 'pe14']) {
    for (const seed of [5, 31337]) {
      const args = { seed, spread: 'celtic', significator: sig };
      draws.push({ args, out: drawReading(args) });
    }
  }
  draws.push({ args: { seed: 11, spread: 'three', cutAt: 0 }, out: drawReading({ seed: 11, spread: 'three', cutAt: 0 }) });
  draws.push({ args: { seed: 11, spread: 'three', cutAt: 80 }, out: drawReading({ seed: 11, spread: 'three', cutAt: 80 }) });
  draws.push({ args: { seed: 11, spread: 'three', cutAt: -3 }, out: drawReading({ seed: 11, spread: 'three', cutAt: -3 }) });
  // recurrences of many celtic draws (only those with at least one recurrence)
  const recur = [];
  for (let s = 0; s < 400 && recur.length < 25; s++) {
    const cards = drawReading({ seed: s, spread: 'celtic' }).cards;
    const r = recurrences(cards);
    if (r.length) recur.push({ cards: cards.map(({ id, reversed }) => ({ id, reversed })), out: r });
  }
  return {
    _doc: 'Generated by tools/make_engine_fixture.mjs from static/engine.js; checked by tests/engine_fixture.test.mjs (JS) and tests/test_web.py (Python port).',
    deck: CARDS,
    spreads: SPREADS,
    rng: rngs,
    seedFrom: texts.map(t => [t, seedFrom(t)]),
    shuffle: [1, 42, 4294967295].map(s => [s, shuffle(ids, rng(s))]),
    cut: [[2, cut(ids, 2)], [77, cut(ids, 77)], [-1, cut(ids, -1)]],
    draws,
    recurrences: recur,
  };
}

export const fixtureText = () => JSON.stringify(fixture(), null, 1) + '\n';

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === fixtureText();
    console.log(same ? 'fixture is current' : 'fixture is out of date: run node tools/make_engine_fixture.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, fixtureText());
  console.log('wrote', OUT.pathname);
}
